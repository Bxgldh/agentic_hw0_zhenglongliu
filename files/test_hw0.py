def test_part3_tool_error_is_short_and_does_not_leak():
    from part3_errors import DeliveryOrder, to_tool_error

    with pytest.raises(ValidationError) as info:
        DeliveryOrder.model_validate(
            {
                "item": "sushi",
                "quantity": 500,
                "spice": "nuclear",
                "fulfillment": "delivery",
                "address": "the Moon",
            }
        )
    err = to_tool_error(info.value)

    assert err.code in {"invalid_arguments", "outside_delivery_zone"}
    assert len(err.message) <= 200
    assert "errors.pydantic.dev" not in err.message
    assert "DeliveryOrder" not in err.message
    assert "input_value" not in err.message
    assert set(err.fields) >= {"item", "quantity", "spice", "address"}


