"""
The specification for HW 0, written as automated tests.

WHAT THIS FILE IS FOR

Every requirement in the assignment appears here as a test with a descriptive
name. When a TODO's instructions are ambiguous, the tests are the answer: they
are what the graders run.

HOW TO USE IT

    pytest -q            run everything, quietly
    pytest -q -k part2   run only the Part 2 tests, while you work on Part 2
    pytest -x            stop at the first failure

Run it as often as you like. Before you start, expect about 31 failures. That is
correct: the failures are the assignment, and they disappear one TODO at a time.

Do not edit this file. If a test seems wrong, say so in ANSWERS.md and explain
why; that is worth more than a passing test.

Note that no test here can check whether an order was the *right* order, only
whether it was well formed. Holding on to that distinction is the point of Q6.
"""

