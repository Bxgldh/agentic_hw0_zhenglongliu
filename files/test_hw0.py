@pytest.fixture(autouse=True)
def _clean_ledger():
    """Empty the cash register before and after every test.

    `autouse=True` means pytest applies this to every test in the file without
    being asked. Several tests below check that nothing was charged, so they
    each need to start from zero.
    """
    taqueria.reset_ledger()
    yield
    taqueria.reset_ledger()


def test_part4_good_order_goes_through():
    from part4_tool_boundary import OrderResult, handle_tool_call

    result = handle_tool_call(
        "place_order",
        {"item": "burrito", "quantity": 2, "spice": "mild", "fulfillment": "pickup"},
    )
    assert isinstance(result, OrderResult)
    assert result.status == "confirmed"
    assert result.total_usd == pytest.approx(25.00)
    assert result.order_id.startswith("ORD-")
    assert taqueria.total_charged() == pytest.approx(25.00)


